// Verify all languages have the same keys
function verifyTranslations() {
    const languages = Object.keys(i18nData);
    if (languages.length === 0) {
        console.error('No languages found in i18nData');
        return;
    }
    
    const baseLang = languages[0];
    const baseKeys = Object.keys(i18nData[baseLang]);
    
    languages.forEach(lang => {
        const langKeys = Object.keys(i18nData[lang]);
        const missingKeys = baseKeys.filter(key => !langKeys.includes(key));
        if (missingKeys.length > 0) {
            console.warn(`Language "${lang}" is missing keys:`, missingKeys);
        }
    });
}

// Run verification
verifyTranslations();

// i18n Core Functions
const i18n = {
    currentLang: 'en',
    
    init() {
        // Get saved language from localStorage or default to 'en'
        const savedLang = localStorage.getItem('preferredLanguage') || 'en';
        this.setLanguage(savedLang);
        
        // Setup language selector
        this.setupLanguageSelector();
    },
    
    setLanguage(lang) {
        if (!i18nData[lang]) {
            console.warn(`Language ${lang} not found, defaulting to 'en'`);
            console.warn('Available languages:', Object.keys(i18nData));
            lang = 'en';
        }
        
        this.currentLang = lang;
        localStorage.setItem('preferredLanguage', lang);
        document.documentElement.lang = lang === 'zh' ? 'zh-CN' : (lang === 'fr' ? 'fr-FR' : lang);
        
        // Translate all elements with data-i18n attribute
        document.querySelectorAll('[data-i18n]').forEach(element => {
            const key = element.getAttribute('data-i18n');
            const translation = this.t(key);
            
            if (element.tagName === 'INPUT' && (element.type === 'text' || element.type === 'textarea')) {
                element.placeholder = translation;
            } else if (element.tagName === 'IMG') {
                element.alt = translation;
            } else {
                element.textContent = translation;
            }
        });
        
        // Translate elements with data-i18n-html for HTML content
        document.querySelectorAll('[data-i18n-html]').forEach(element => {
            const key = element.getAttribute('data-i18n-html');
            const translation = this.t(key);
            element.innerHTML = translation.replace(/\n/g, '<br>');
        });
        
        // Translate placeholder attributes
        document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
            const key = element.getAttribute('data-i18n-placeholder');
            element.placeholder = this.t(key);
        });
        
        // Update language selector active state
        this.setupLanguageSelector();
    },
    
    t(key) {
        const keys = key.split('.');
        let value = i18nData[this.currentLang];
        
        for (const k of keys) {
            if (value && value[k]) {
                value = value[k];
            } else {
                console.warn(`Translation key "${key}" not found for language "${this.currentLang}"`);
                return key;
            }
        }
        
        return value || key;
    },
    
    setupLanguageSelector() {
        const selector = document.querySelector('.language-selector');
        if (!selector) {
            console.warn('Language selector not found');
            return;
        }
        
        // Remove all existing event listeners by replacing innerHTML
        const currentLang = this.currentLang;
        selector.innerHTML = `
            <span class="lang-option ${currentLang === 'en' ? 'active' : ''}" data-lang="en">EN</span> | 
            <span class="lang-option ${currentLang === 'zh' ? 'active' : ''}" data-lang="zh">中</span> | 
            <span class="lang-option ${currentLang === 'fr' ? 'active' : ''}" data-lang="fr">FR</span>
        `;
        
        // Bind click events to all lang-option elements
        const langOptions = selector.querySelectorAll('.lang-option');
        const self = this; // Store reference to i18n object
        langOptions.forEach(option => {
            option.style.cursor = 'pointer';
            option.addEventListener('click', function(e) {
                e.preventDefault();
                e.stopPropagation();
                const lang = this.getAttribute('data-lang');
                if (lang && i18nData[lang]) {
                    self.setLanguage(lang);
                } else {
                    console.error(`Language "${lang}" not found in i18nData`);
                }
            });
        });
    }
};

// Initialize i18n when DOM is ready
(function initI18n() {
    function initialize() {
        i18n.init();
    }
    
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', initialize);
    } else {
        // DOM already loaded
        initialize();
    }
})();

// Make i18n available globally
window.i18n = i18n;
